"""Puente Orbit para el dashboard. No descarga ni interpreta enlaces.

SOLO montado bajo /orbit-bridge/zero/. El destino es fijo y el acceso
requiere las credenciales existentes del dashboard; nunca acepta destinos de
red enviados por el navegador. Soporta HTTP y WebSockets.
"""
from __future__ import annotations

import http.client
import json
import orbit_devices
import io
import os
import re
import select
import socket
import urllib.parse
from request_security import same_origin, allowed_mutation

PROXY_PREFIX = "/orbit-bridge/"
ZERO_HOST, ZERO_PORT = "127.0.0.1", 34179
PS5_PORT = 34177
MAX_REQUEST_BYTES = 20 * 1024 * 1024


def _target(request_path):
    parsed = urllib.parse.urlsplit(request_path)
    match = re.match(r"^/orbit-bridge/(zero)(?:/(.*))?$", parsed.path)
    if not match: return None
    mode, tail = match.groups()
    relative = "/" + (tail or "")
    if parsed.query: relative += "?" + parsed.query
    return mode, ZERO_HOST, ZERO_PORT, relative


def _base(mode):
    return PROXY_PREFIX + mode + "/"


def _rewrite_location(location, mode, host, port):
    base = _base(mode)
    value = str(location)
    if value.startswith("/") and not value.startswith("//"):
        return base + value.lstrip("/")
    parsed = urllib.parse.urlsplit(value)
    if parsed.scheme in ("http", "https", "ws", "wss") and parsed.hostname == host and parsed.port == port:
        path = base + parsed.path.lstrip("/")
        return urllib.parse.urlunsplit(("", "", path, parsed.query, parsed.fragment))
    return value


def _replace_root_refs(html, mode):
    base = _base(mode)
    # Relative HTML paths use <base>; root-absolute static resources need prefix.
    html = re.sub(r'((?:src|href|action|content)\s*=\s*["\'])/(?!/)', lambda m: m.group(1) + base, html, flags=re.I)
    # Prepend before all other scripts so fetch, XHR, WebSocket and EventSource
    # generated by application code also follow the same dashboard origin.
    bootstrap = '<script src="' + base + '__bridge.js"></script><script defer src="' + base + '__devices.js"></script><link rel="stylesheet" href="' + base + '__devices.css">'
    # Explicit base makes relative SPA script/css URLs follow the proxy.
    injection = '<base href="' + base + '">' + bootstrap
    if re.search(r'<head\b[^>]*>', html, flags=re.I):
        html = re.sub(r'(<head\b[^>]*>)', lambda m: m.group(1) + injection, html, count=1, flags=re.I)
    else:
        html = injection + html
    return html


def _rewrite_cookie(cookie, mode):
    base = _base(mode)
    if re.search(r"(?i)(^|;)\s*path=", cookie):
        return re.sub(r"(?i)(;\s*path=)[^;]*", lambda m: m.group(1) + base, cookie, count=1)
    return cookie + "; Path=" + base


def _proxy_headers(handler, mode, host, port):
    filtered = {}
    excluded = {"host", "connection", "accept-encoding", "transfer-encoding", "content-length", "proxy-authorization", "authorization", "x-orbit-control-password", "x-orbit-pair-password", "x-orbit-action", "x-dashboard-action", "cookie", "origin", "referer", "forwarded", "x-forwarded-host", "x-forwarded-proto", "x-forwarded-for"}
    for key, val in handler.headers.items():
        if key.lower() not in excluded and not key.lower().startswith("sec-websocket"):
            filtered[key] = val
    filtered["Host"] = f"{host}:{port}"
    filtered["Accept-Encoding"] = "identity"
    filtered["Origin"] = f"http://{host}:{port}"
    filtered["Referer"] = f"http://{host}:{port}/"
    # Orbit pairing cookies belong to /orbit-bridge/mode and cannot reach
    # unrelated dashboard APIs; the dashboard Basic token is never forwarded.
    cookie = orbit_devices.cookie_header(handler.headers)
    if cookie:
        filtered['Cookie'] = cookie
    return filtered


def _response_headers(handler, upstream_headers, mode, host, port, size, content_type):
    blocked = {"content-length", "transfer-encoding", "connection", "keep-alive", "proxy-authenticate", "proxy-authorization", "te", "trailer", "upgrade", "x-frame-options", "content-encoding", "content-security-policy", "access-control-allow-origin", "access-control-allow-credentials", "cache-control", "expires"}
    for key,val in upstream_headers:
        lk = key.lower()
        if lk == "location":
            val = _rewrite_location(val,mode,host,port)
        if lk == "set-cookie":
            if orbit_devices.token(handler.headers):
                if orbit_devices.accept_manual_session(handler.headers, val):
                    continue
                handler.send_header('Set-Cookie', orbit_devices.COOKIE + '=; Max-Age=0; Path=/; HttpOnly; Secure; SameSite=Strict')
            val = _rewrite_cookie(val,mode)
        if lk not in blocked:
            handler.send_header(key,val)
    # Use the original security policy except its frame-ancestors directive.
    for key,val in upstream_headers:
        if key.lower() == 'content-security-policy':
            policy = ';'.join(x for x in val.split(';') if not x.strip().lower().startswith('frame-ancestors'))
            handler.send_header('Content-Security-Policy', policy + "; frame-ancestors 'self'")
    # Cache only public-looking static assets, privately per browser.
    # HTML/API/JSON, auth, pairing and all state responses stay no-store.
    asset = content_type.split(';', 1)[0].strip().lower()
    if asset.startswith('image/') or asset.startswith('font/') or asset in ('application/font-woff', 'application/font-woff2'):
        cache = 'private, max-age=1800'
    elif asset in ('text/css', 'text/javascript', 'application/javascript'):
        cache = 'private, max-age=300'
    else:
        cache = 'no-store'
    handler.send_header('Cache-Control', cache)
    handler.send_header("X-Content-Type-Options", "nosniff")
    handler.send_header("Content-Length",str(size))


def _send_error(handler,status,message):
    body = message.encode('utf-8')
    handler.send_response(status)
    handler.send_header('Content-Type','text/plain; charset=utf-8')
    handler.send_header('Cache-Control','no-store')
    handler.send_header('Content-Length',str(len(body)))
    handler.end_headers()
    if handler.command!='HEAD': handler.wfile.write(body)


def serve(handler):
    """Return True only for requests in the Orbit namespace."""
    target = _target(handler.path)
    if target is None:
        return False
    mode,host,port,path = target
    # Mandatory authentication, even if the dashboard itself allows localhost
    # without login; a local reverse proxy could otherwise expose Orbit.
    import sys
    parent = sys.modules[handler.__class__.__module__]
    user = getattr(parent,'DASHBOARD_USER','')
    password = getattr(parent,'DASHBOARD_PASSWORD','')
    if not (user and password):
        _send_error(handler,503,'Para integrar Orbit configura DASHBOARD_USER y DASHBOARD_PASSWORD en el .env del dashboard.');return True
    if not handler._require_auth(): return True
    websocket = handler.headers.get('Upgrade', '').lower() == 'websocket'
    if ((websocket and not same_origin(handler.headers))
            or (handler.command not in ('GET', 'HEAD', 'OPTIONS') and not allowed_mutation(handler.headers))):
        _send_error(handler, 403, 'Origen no autorizado'); return True
    if path.split('?',1)[0] in ('/__bridge.js', '/__devices.js', '/__devices.css') and handler.command in ('GET','HEAD'):
        from pathlib import Path
        filename = {'/__bridge.js': 'orbit_bridge_shim.js', '/__devices.js': 'orbit_devices.js', '/__devices.css': 'orbit_devices.css'}[path.split('?',1)[0]]
        contents=(Path(__file__).resolve().with_name(filename)).read_bytes()
        handler.send_response(200)
        handler.send_header('Content-Type', ('text/css' if filename.endswith('.css') else 'application/javascript') + '; charset=utf-8')
        handler.send_header('Cache-Control','no-store')
        handler.send_header('Content-Length',str(len(contents)))
        handler.end_headers()
        if handler.command != 'HEAD': handler.wfile.write(contents)
        return True
    if handler.headers.get('Upgrade','').lower() == 'websocket':
        _websocket(handler,mode,host,port,path)
    else:
        _http(handler,mode,host,port,path)
    return True


def _http(handler,mode,host,port,path):
    length_raw = handler.headers.get('Content-Length','0')
    try: length = int(length_raw)
    except ValueError: length = -1
    if length < 0 or length > MAX_REQUEST_BYTES or handler.headers.get('Transfer-Encoding'):
        _send_error(handler,413,'Tamaño de solicitud no permitido');return
    data=handler.rfile.read(length) if length else None
    client=http.client.HTTPConnection(host,port,timeout=25)
    try:
        h=_proxy_headers(handler,mode,host,port)
        client.request(handler.command,path,body=data,headers=h)
        response=client.getresponse()
        body=response.read(MAX_REQUEST_BYTES+1)
        if len(body)>MAX_REQUEST_BYTES:
            _send_error(handler,502,'Respuesta del servicio Orbit demasiado grande');return
        if handler.command == 'GET' and path.split('?', 1)[0] == '/api/state' and response.status == 200:
            try:
                needs_pairing = json.loads(body).get('needsPairing') is True
            except (ValueError, AttributeError):
                needs_pairing = False
            if needs_pairing and orbit_devices.recover(handler.headers):
                client.close()
                client = http.client.HTTPConnection(host, port, timeout=25)
                client.request('GET', path, headers=_proxy_headers(handler,mode,host,port))
                response = client.getresponse()
                body = response.read(MAX_REQUEST_BYTES + 1)
                if len(body) > MAX_REQUEST_BYTES:
                    _send_error(handler,502,'Respuesta del servicio Orbit demasiado grande'); return
        upstream_headers=response.getheaders()
        enc=response.getheader('Content-Encoding','').lower()
        if enc == 'gzip':
            import gzip
            try:
                with gzip.GzipFile(fileobj=io.BytesIO(body)) as compressed:
                    body=compressed.read(MAX_REQUEST_BYTES+1)
            except (OSError, ValueError):
                _send_error(handler,502,'Respuesta comprimida invalida');return
            if len(body)>MAX_REQUEST_BYTES:
                _send_error(handler,502,'Respuesta descomprimida demasiado grande');return
        elif enc and enc!='identity':
            _send_error(handler,502,'Codificación Orbit no compatible');return
        ct=response.getheader('Content-Type','').lower()
        if 'text/html' in ct and body:
            text=body.decode('utf-8','replace')
            body=_replace_root_refs(text,mode).encode('utf-8')
        elif 'text/css' in ct and body:
            css=body.decode('utf-8','replace')
            # CSS url('/art/...') ignores HTML <base>.
            css=re.sub(r"""url\(\s*(["']?)/(?!/)""",
                       lambda m: 'url(' + m.group(1) + _base(mode), css, flags=re.I)
            body=css.encode('utf-8')
        handler.send_response(response.status)
        _response_headers(handler,upstream_headers,mode,host,port,len(body),ct)
        handler.end_headers()
        if handler.command!='HEAD': handler.wfile.write(body)
    except (OSError,TimeoutError,http.client.HTTPException) as exc:
        _send_error(handler,502,'No se puede contactar con Orbit en el equipo configurado.')
    finally:
        client.close()


def _websocket(handler,mode,host,port,path):
    remote=None
    try:
        remote=socket.create_connection((host,port),timeout=10)
        lines=[f'GET {path} HTTP/1.1',f'Host: {host}:{port}',f'Origin: http://{host}:{port}', 'Connection: Upgrade','Upgrade: websocket']
        for k in ['Sec-WebSocket-Key','Sec-WebSocket-Version','Sec-WebSocket-Protocol']:
            if handler.headers.get(k):lines.append(f'{k}: {handler.headers[k]}')
        cookie = orbit_devices.cookie_header(handler.headers)
        if cookie: lines.append('Cookie: ' + cookie)
        remote.sendall(('\r\n'.join(lines)+'\r\n\r\n').encode('latin-1'))
        head=b''
        while b'\r\n\r\n' not in head and len(head)<16384:
            block=remote.recv(4096)
            if not block:break
            head+=block
        if b'\r\n\r\n' not in head: raise OSError('Handshake incompleto')
        header,rest=head.split(b'\r\n\r\n',1)
        if not header.startswith(b'HTTP/1.1 101') and not header.startswith(b'HTTP/1.0 101'):
            _send_error(handler,502,'Orbit rechazó la conexión WebSocket');return
        # Preserve the accepted WebSocket handshake; do not propagate secrets
        handler.connection.sendall(header+b'\r\n\r\n'+rest)
        handler.close_connection=True
        remote.settimeout(None)
        handler.connection.settimeout(None)
        sockets=[remote,handler.connection]
        while True:
            ready,_,_=select.select(sockets,[],[],60)
            if not ready:break
            for s in ready:
                chunk=s.recv(65536)
                if not chunk:return
                (handler.connection if s is remote else remote).sendall(chunk)
    except (OSError,TimeoutError):
        if remote is None:
            _send_error(handler,502,'No se puede conectar al WebSocket de Orbit')
    finally:
        if remote:remote.close()
        handler.close_connection=True
